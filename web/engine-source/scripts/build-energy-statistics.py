#!/usr/bin/env python3
"""Rebuild the exact float32 pairwise SIMD kernel with LLVM 23.1.0."""
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

root = Path(__file__).resolve().parent.parent
clang = os.environ.get('CLANG') or shutil.which('clang')
linker = os.environ.get('WASM_LD') or shutil.which('wasm-ld')
if not clang or not linker:
    raise SystemExit('LLVM 23.1.0 clang and wasm-ld are required (CLANG/WASM_LD).')
for tool in [clang, linker]:
    version = subprocess.check_output([tool, '--version'], text=True).splitlines()[0]
    if not re.search(r'\b23\.1\.0\b', version):
        raise SystemExit('The reproducible kernel requires LLVM clang/lld 23.1.0.')
source = root / 'native/energy-statistics.c'
destination = root / 'vendor/energy-statistics'
destination.mkdir(parents=True, exist_ok=True)
flags = ['--target=wasm32', '-O3', '-msimd128', '-nostdlib', '-fno-ident',
         '-fvisibility=hidden', '-fno-fast-math', '-ffp-contract=off',
         '-fno-associative-math', '-fno-unsafe-math-optimizations',
         '-ffile-prefix-map=' + str(root) + '=.',
         '-fdebug-prefix-map=' + str(root) + '=.']
links = ['--no-entry', '--import-memory', '--export=energy_pairwise', '--export=energy_filter',
         '--export=__heap_base', '--stack-first', '--strip-all',
         '--initial-memory=65536', '--max-memory=65536', '-z', 'stack-size=16384']
with tempfile.TemporaryDirectory(prefix='sherloq-energy-statistics-') as directory:
    obj = Path(directory) / 'statistics.o'
    subprocess.run([clang, *flags, '-c', str(source), '-o', str(obj)], check=True)
    subprocess.run([linker, *links, str(obj), '-o', str(destination / 'statistics.wasm')], check=True)
binary = (destination / 'statistics.wasm').read_bytes()
digest = hashlib.sha256(binary).hexdigest()
pin = {'schema': 'sherloq.energy-statistics-kernel/1', 'bytes': len(binary),
       'sha256': digest, 'source': 'native/energy-statistics.c',
       'sourceSha256': hashlib.sha256(source.read_bytes()).hexdigest(),
       'build': 'scripts/build-energy-statistics.py', 'llvm': '23.1.0',
       'compileFlags': [f for f in flags if 'prefix-map' not in f], 'linkFlags': links,
       'memory': {'imported': True, 'pages': 1, 'maximumPages': 1,
                  'stackBytes': 16384, 'inputFloatsMaximum': 8192,
                  'heapBaseMaximum': 32768},
       'algorithm': 'numpy-f32-pairwise8-split-aligned8-no-fma-stable-filter4'}
(destination / 'PINNED.json').write_text(json.dumps(pin, indent=2) + '\n')
shutil.copyfile(root / 'LICENSE', destination / 'LICENSE')
(root / 'src/energy-statistics-kernel-pin.js').write_text(
    '// Generated by scripts/build-energy-statistics.py; verify before instantiation.\n'
    'export const ENERGY_STATISTICS_KERNEL=Object.freeze({\n'
    " url:new URL('../vendor/energy-statistics/statistics.wasm',import.meta.url).href,\n"
    f" bytes:{len(binary)},sha256:'{digest}'\n"
    '});\n')
print(json.dumps({'bytes': len(binary), 'sha256': digest, 'llvm': '23.1.0'}))

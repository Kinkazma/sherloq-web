#!/usr/bin/env python3
"""Build the freestanding exact byte-median SIMD kernel with LLVM 23.1.0.

Set CLANG and WASM_LD when the pinned tools are not on PATH. No SDK, libc,
download, floating-point option, or external dependency enters this build.
"""
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

root = Path(__file__).resolve().parent.parent
clang = os.environ.get("CLANG") or shutil.which("clang")
linker = os.environ.get("WASM_LD") or shutil.which("wasm-ld")
if not clang or not linker:
    raise SystemExit("LLVM 23.1.0 clang and wasm-ld are required (CLANG/WASM_LD).")
clang_version = subprocess.check_output([clang, "--version"], text=True).splitlines()[0]
linker_version = subprocess.check_output([linker, "--version"], text=True).splitlines()[0]
if not all(re.search(r"\b23\.1\.0\b", version) for version in [clang_version, linker_version]):
    raise SystemExit("The reproducible kernel requires LLVM clang/lld 23.1.0.")
source = root / "native/ela-synthesis-median.c"
destination = root / "vendor/ela-synthesis-median"
destination.mkdir(parents=True, exist_ok=True)
flags = ["--target=wasm32", "-O3", "-msimd128", "-nostdlib", "-fno-ident",
         "-fvisibility=hidden", "-ffile-prefix-map=" + str(root) + "=.",
         "-fdebug-prefix-map=" + str(root) + "=."]
link_flags = ["--no-entry", "--import-memory", "--export=median_block",
              "--strip-all", "-z", "stack-size=16384"]
with tempfile.TemporaryDirectory(prefix="sherloq-byte-median-") as directory:
    obj = Path(directory) / "median.o"
    subprocess.run([clang, *flags, "-c", str(source), "-o", str(obj)], check=True)
    subprocess.run([linker, *link_flags, str(obj), "-o", str(destination / "median.wasm")], check=True)

binary = (destination / "median.wasm").read_bytes()
digest = hashlib.sha256(binary).hexdigest()
pin = {"schema": "sherloq.ela-synthesis-median-kernel/1", "bytes": len(binary),
       "sha256": digest, "source": "native/ela-synthesis-median.c",
       "sourceSha256": hashlib.sha256(source.read_bytes()).hexdigest(),
       "build": "scripts/build-ela-synthesis-median.py", "llvm": "23.1.0",
       "compileFlags": [flag for flag in flags if "prefix-map" not in flag],
       "linkFlags": link_flags, "memory": {"imported": True, "stackBytes": 16384},
       "algorithm": "exact-byte-order-statistic-simd16-u16-count256"}
(destination / "PINNED.json").write_text(json.dumps(pin, indent=2) + "\n")
shutil.copyfile(root / "LICENSE", destination / "LICENSE")
(root / "src/ela-synthesis-median-kernel-pin.js").write_text(
    "// Generated by scripts/build-ela-synthesis-median.py; verify before instantiation.\n"
    "export const ELA_SYNTHESIS_MEDIAN_KERNEL=Object.freeze({\n"
    " url:new URL('../vendor/ela-synthesis-median/median.wasm',import.meta.url).href,\n"
    f" bytes:{len(binary)},sha256:'{digest}'\n"
    "});\n")
print(json.dumps({"bytes": len(binary), "sha256": digest, "llvm": "23.1.0"}))

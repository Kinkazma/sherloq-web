"""Export complete pinned PyWavelets banks for the optional IDWT GPU transport.

Requires PyWavelets 1.5.0 and its original source archive. It does not change
native decomposition or threshold functions, wavelet families or filter taps.
"""
from pathlib import Path
import hashlib,json,os,tarfile
import pywt

root=Path(__file__).resolve().parents[1]
archive=Path(os.environ.get('PYWT_ARCHIVE',root/'.build/pywt-1.5.0.tar.gz'))
expected='5aedfa9bd629f104a04fda88b92582bda38ab22282ce5048b5760b5d18e83fc9'
if pywt.__version__!='1.5.0':raise RuntimeError('PyWavelets1.5.0 is required')
if hashlib.sha256(archive.read_bytes()).hexdigest()!=expected:raise RuntimeError('PyWavelets archive identity differs')
names=['db'+str(i) for i in range(1,21)]+['sym'+str(i) for i in range(2,21)]+['coif'+str(i) for i in range(1,6)]+['bior'+i for i in ['1.1','1.3','1.5','2.2','2.4','2.6','2.8','3.1','3.3','3.5','3.7','3.9','4.4','5.5','6.8']]
banks={name:pywt.Wavelet(name).filter_bank for name in names}
target=root/'src/wavelet-gpu-banks.js'
target.write_text('// Generated by scripts/build-wavelet-gpu-banks.py from pinned PyWavelets1.5.0.\n// Full native filter banks; no coefficient thresholding or filter substitution.\nexport const waveletGpuBanks='+json.dumps(banks,separators=(',',':'))+';\n')
out=root/'vendor/wavelet-gpu';out.mkdir(parents=True,exist_ok=True)
with tarfile.open(archive) as source:
    license_bytes=source.extractfile('pywt-1.5.0/LICENSE').read()
    (out/'LICENSE').write_bytes(license_bytes)
(out/'PINNED.json').write_text(json.dumps({'PyWavelets':'1.5.0','archiveSha256':expected,'waveletFamilies':len(names),'filterBanks':'Complete binary64 native dec_lo,dec_hi,rec_lo,rec_hi coefficients; high/low encoding happens only in GPU transport','files':{'src/wavelet-gpu-banks.js':hashlib.sha256(target.read_bytes()).hexdigest(),'LICENSE':hashlib.sha256(license_bytes).hexdigest()}},indent=2)+'\n')
